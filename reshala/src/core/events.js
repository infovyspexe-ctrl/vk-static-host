// Механика вешает объявление: bus.emit('match3:cleared', { type: 'apple', count: 3 });
// Кто угодно его слушает:     bus.on('match3:cleared', (data) => { /* начислить монеты */ });
// Так механика не знает, кто её слушает, и её легко перенести в другую игру.
