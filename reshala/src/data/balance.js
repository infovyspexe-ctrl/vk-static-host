export const BALANCE = {
  // Рост сложности в бесконечном режиме: множитель к дельтам scale-шкал.
  // День 1 → 1.0, дальше +6% в день, максимум +150%. Подобрано симулятором
  // (library-подход «баланс считаем, не на глаз»): оптимал-бот в «Сроке» живёт
  // ~52 дня медиана с хвостом до ~380 (лидерборд имеет смысл, бесконечности нет).
  difficultyPerDay: 0.06,
  difficultyCap: 1.5,

  // Раз во сколько дней гарантированно приходит карта с мини-игрой.
  // Без расписания их практически не видно: мини-игра есть на 6 картах из 86 и только
  // на одной стороне — ожидание 0.5 мини-игры за 15 дней, больше половины игроков
  // не встречали ни одной (жалоба с живого прохождения).
  miniEvery: 5,

  // Сцена: сколько карт подряд держатся одного собеседника или одного места.
  // Без этого игрок скачет камера → столовая → двор без причины («переходы непонятны»,
  // жалоба с живого прохождения). chance — вероятность продолжить сцену, max — потолок
  // подряд, чтобы один и тот же повар не заговорил игрока насмерть.
  stickChance: 0.6,
  stickMax: 3,

  // Порог свайпа: сколько px утащить карту, чтобы решение засчиталось.
  swipeThreshold: 90,

  // Межстраничная реклама: раз во столько карт (на естественном перерыве — после того как игрок
  // прочитал реакцию и до следующей карты, не во время действия — требование модерации C3).
  // Карта ~4 с, так что 18 ≈ раз в ~70 с; Яндекс всё равно не покажет чаще раза в 60 с, поэтому
  // это мягкая цель, а не жёсткая частота. В ПЕРВОМ забеге игрока реклама не показывается вовсе
  // (даём чистое первое впечатление — RETENTION: первая награда раньше первой рекламы).
  adEveryCards: 18,

  // Коллекция: сколько раз встретить персонажа, чтобы открылось полное досье.
  // 1..friendAt-1 встреч — силуэт открыт (имя+эмодзи), но досье скрыто; >=friendAt — «подружился».
  friendAt: 3,
};

// Функция роста сложности (передаётся движку как scaleEffects).
export function difficultyFactor(day) {
  return 1 + Math.min((day - 1) * BALANCE.difficultyPerDay, BALANCE.difficultyCap);
}

// ── БЛОЧНЫЙ СЮЖЕТ (спека 2026-07-18) ─────────────────────────────────────────
// Движок reigns читает { count, final, length, escape, cycleUnseen } (см. шапку reigns.js).
// Один пул карт кормит оба режима: «Побег» тянет короткими блоками с картой побега на границе,
// «Срок» — длинными блоками без побега, после финала — по кругу с невиданными картами.
// Числа ОТКАЛИБРОВАНЫ симулятором (tools/balance_sim.mjs, блочный раздел), не на глаз.
export const BLOCKS = {
  count: 10,        // всего блоков
  final: 10,        // финальный блок: карты побега там только победные
  // длина блока (survival-карт до границы) — своя на режим:
  length: {
    campaign: { min: 5, max: 10 },   // «Побег»: короткий блок + карта побега на границе
    endless: { min: 15, max: 20 },   // «Срок»: длинный блок, карт побега нет
  },

  // Рост сложности в БЛОЧНОЙ КАМПАНИИ — почти выключен, и это не небрежность.
  // Прежняя кривая (difficultyPerDay 0.06) считалась под бесконечный «Срок», где смерть —
  // смысл режима и лидерборд. В кампании дожить надо ~9 блоков (~65 карт), и на 50-м дне
  // дельты множились на 2.5: симулятор показал winPct 16% у игрока, выбирающего побег вслепую,
  // — до гарантированно-победного финала не доживал почти никто (цель спеки: слабый доходит
  // до блока 10 и там побеждает). При 0.01 получаем 70% побед, медиана победы — 7-й блок.
  // «Срок» свою крутую кривую сохраняет (см. BALANCE.difficultyPerDay).
  difficultyPerDay: 0.01,
  difficultyCap: 0.5,
};

// Рост сложности для блочной кампании (передаётся движку вместо difficultyFactor).
export function blockDifficultyFactor(day) {
  return 1 + Math.min((day - 1) * BLOCKS.difficultyPerDay, BLOCKS.difficultyCap);
}

// Собрать конфиг блоков для движка под конкретный режим (передаётся в createReigns как config.blocks).
export function blocksConfig(mode) {
  const campaign = mode === 'campaign';
  return {
    count: BLOCKS.count,
    final: BLOCKS.final,
    length: campaign ? BLOCKS.length.campaign : BLOCKS.length.endless,
    escape: campaign,          // карта побега на границе только в «Побеге»
    cycleUnseen: !campaign,    // «Срок» после финала идёт по кругу
  };
}
