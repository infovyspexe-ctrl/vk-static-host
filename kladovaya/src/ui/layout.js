// РАСКЛАДКА UI. Общее место, где живут прямоугольники кнопок: render.js рисует
// по ним, game.js проверяет попадание тапа. Оверлеи (конец партии, кладовая)
// вписывают свои кнопки сюда при отрисовке — ввод всегда сверяется с тем,
// что реально нарисовано.
import { CONFIG } from '../data/config.js';

export const LAYOUT = {
  // Статичные элементы HUD (кнопки укрупнены под аудиторию 45+)
  sound: { x: 616, y: 20, w: 84, h: 84 },
  pantryBtn: { x: 616, y: 112, w: 84, h: 84 },
  jar: { x: 516, y: 40, w: 88, h: 128 },      // банка-шкала (тап, когда готова)
  nextPreview: { x: CONFIG.W / 2, y: 96 },     // центр превью следующего плода
  order: { x: 16, y: 122, w: 208, h: 96 },     // доска заказа (коллекции)
  daily: { x: 16, y: 226, w: 208, h: 46 },     // плашка «банка дня»
  pantryPanel: { x: 40, y: 120, w: CONFIG.W - 80, h: 1040 }, // панель оверлея кладовой

  // Кнопки активного оверлея: [{ id, x, y, w, h }]. Заполняет render каждый кадр,
  // когда оверлей открыт; пустой список — оверлея нет.
  overlayButtons: [],

  // pad — допуск попадания: палец 45+ не обязан попадать пиксель в пиксель.
  // 8px с каждой стороны меньше половины любого зазора между кнопками.
  hit(rect, x, y, pad = 8) {
    return rect && x >= rect.x - pad && x <= rect.x + rect.w + pad &&
      y >= rect.y - pad && y <= rect.y + rect.h + pad;
  },

  overlayHit(x, y) {
    for (const b of this.overlayButtons) {
      if (this.hit(b, x, y)) return b.id;
    }
    return null;
  }
};
