// Коллекция цветов машин: s.collection[tierId] — массив bool по индексу варианта
// (TIERS[i].variants). true = хоть раз вымыт ИЛИ куплен напрямую за гемы (ECONOMY.skinCost).
// Помогает функция ниже — тир «собран», если все варианты true.
function tierCollected(s, tierId) {
  const arr = s.collection && s.collection[tierId];
  return !!arr && arr.length > 0 && arr.every(Boolean);
}
function allCollected(s) {
  return TIERS.every((t) => tierCollected(s, t.id));
}

