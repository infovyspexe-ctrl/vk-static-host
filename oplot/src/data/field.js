// Константы поля и партии. Все числа баланса — только здесь, сцены их не дублируют.
export const FIELD = {
  gap: 6,        // пустых клеток между правым краём базы игрока и левым краём врага
  startGold: 85, // кошелёк новой партии: хватит на пушку или четвёрку лучников

  // Рост платформы по главам (спека, раздел 6): 12 клеток в первой главе,
  // +2 каждые 10 уровней, потолок 20. Капается геометрией поля, а не произволом —
  // выше 20 клеток разметка на телефонном экране становится нечитаемой.
  baseWidth: 12,
  widthStep: 2,
  widthCap: 20,
};

// Глава — это каждые 10 уровней. Платформа растёт с новой главой и не сокращается
// (проверено в progress.test.js — growToLevel никогда не уменьшает ширину).
export function widthForLevel(level) {
  const grown = FIELD.baseWidth + FIELD.widthStep * Math.floor((level - 1) / 10);
  return Math.min(grown, FIELD.widthCap);
}
