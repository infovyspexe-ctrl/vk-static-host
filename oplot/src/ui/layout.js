// РАСКЛАДКА ПОД ДВЕ ОРИЕНТАЦИИ. Единственное место, которое знает, где что стоит.
//
// Зачем модуль вообще есть. Раскладка «в долях от height» выглядит переносимой, но ею
// не является: в портрете дефицит по ШИРИНЕ и запас по высоте, в альбоме ровно наоборот.
// Поэтому HUD, набранный полосами сверху и снизу, в альбоме съедает половину поля, а ряд
// кнопок в столбик — весь экран. Перенос игры между ориентациями ломается не на картинках,
// а вот здесь. Сцена спрашивает у layout() именованные области и не считает координаты сама.
//
// Правило, которое модуль кодирует:
//   портрет — HUD полосами сверху/снизу, действия столбиком (ширина дорога, высота дешева);
//   альбом  — HUD колонкой сбоку,       действия рядом      (высота дорога, ширина дешева).
//
// Ориентация игры задаётся в src/main.js (константа ORIENTATION) и объявляется в черновике
// консоли (п.1.6.1.3 требований Яндекса). Здесь она только читается из фактического размера.

// Толщина HUD. Двух долей, а не одной, и это НЕ придирка: полоса и колонка режут разные
// стороны экрана и вмещают разное. Общая доля короткой стороны даёт в альбоме колонку
// 86 px, в которой надпись «Счёт: 0» обрезается по левому краю (поймано скриншотом
// 2026-08-19 на этом же шаблоне). Полоса меряется от высоты, колонка — от ширины.
const HUD_BAR_SHARE = 0.09;   // портрет: горизонтальная полоса, доля ВЫСОТЫ
const HUD_COL_SHARE = 0.20;   // альбом:  вертикальная колонка,  доля ШИРИНЫ

export function layout(scene) {
  const { width: w, height: h } = scene.scale;
  const landscape = w > h;
  const bar = Math.round(landscape ? w * HUD_COL_SHARE : h * HUD_BAR_SHARE);

  // stage — свободное поле под геймплей, из которого HUD уже вычтен. Игровое поле
  // строится ТОЛЬКО по нему, иначе фишки уезжают под панель (ловилось на «Осуши озеро»).
  const stage = landscape
    ? { x: bar, y: 0, w: w - bar, h }
    : { x: 0, y: bar, w, h: h - bar * 2 };
  stage.cx = stage.x + stage.w / 2;
  stage.cy = stage.y + stage.h / 2;

  return {
    w, h, cx: w / 2, cy: h / 2, landscape, bar,
    // Основная полоса HUD: счёт, валюта, таймер.
    hud: landscape
      ? { x: 0, y: 0, w: bar, h, vertical: true }
      : { x: 0, y: 0, w, h: bar, vertical: false },
    // Вторая полоса. В портрете это нижняя кромка (кнопки действий, sticky-баннер площадки) —
    // stage её уже вычел, и класть туда геймплей нельзя. В альбоме второй полосы нет: высота
    // дорога, вторую горизонтальную кромку резать не из чего, поэтому null, а не пустышка —
    // сцена обязана споткнуться явно, а не нарисовать HUD в нулевых координатах.
    hudBottom: landscape ? null : { x: 0, y: h - bar, w, h: bar, vertical: false },
    stage,
    // Группа действий: n кнопок, i — номер с нуля. Возвращает центр i-й кнопки.
    // В портрете группа идёт СТОЛБИКОМ, в альбоме — РЯДОМ; сцена об этом не знает.
    // opts.x / opts.y задают ЦЕНТР ГРУППЫ и работают в обеих ориентациях одинаково,
    // поэтому сцена может опустить меню ниже или поднять выше, не разветвляя код.
    slot(i, n, opts = {}) {
      const gap = opts.gap ?? (landscape ? 260 : 150);
      const mid = (n - 1) / 2;
      const gx = opts.x ?? stage.cx;
      const gy = opts.y ?? (landscape ? stage.y + stage.h * 0.72 : stage.cy);
      return landscape
        ? { x: gx + (i - mid) * gap, y: gy }
        : { x: gx, y: gy + (i - mid) * gap };
    }
  };
}
