// ПОЛНОЭКРАННАЯ РЕКЛАМА НА ПЕРЕХОДЕ — единая точка на всю игру.
//
// Зачем модуль, а не два вызова по месту: интервал между показами обязан быть ОБЩИМ для
// всех переходов. Пока счётчик жил бы в сцене, «конец смены» и «выход в меню» не знали бы
// друг о друге, и игрок, доигравший смену и тут же вышедший в меню, получал бы две рекламы
// подряд — прямой путь к жалобе и к отказу модерации.
//
// Отсчёт (showAdCountdown) обязателен перед ЛЮБЫМ показом, см. большой комментарий в
// adCountdown.js: он и предупреждает игрока (требование Яндекса — показ в логической паузе
// с предупреждением, а не внезапно), и глотает случайный второй тап по тому же месту, где
// игрок только что нажал кнопку перехода, — иначе этот тап уходит уже в рекламу
// (фрод-клик). Так сделано в «Складне», «Мойке снов», «Изнанке», «Красильне» и «Сладкой
// империи»; здесь модуль лежал в папке с 12.08, но не вызывался ни разу — реклама между
// сменами шла без предупреждения, а на выходе в меню её не было вовсе.
import { showAdCountdown } from './adCountdown.js';
import { Ads } from '../yandex/ads.js';
import { ECONOMY } from '../data/balance.js';
import { canShowInterstitial } from '../meta/adPolicy.js';

let lastAt = 0;

/**
 * Показать полноэкранную на логическом переходе и продолжить.
 * @param {Phaser.Scene} scene — сцена, в которой рисуется отсчёт
 * @param {Function} done — что сделать после рекламы (или сразу, если показ пропущен)
 */
export function showInterstitial(scene, done = () => {}) {
  const now = Date.now();
  if (!canShowInterstitial(now, lastAt, ECONOMY.interstitialIntervalMs)) { done(); return; }
  lastAt = now;
  // Момент отсчитывается ОТ НАЧАЛА показа, а не от конца: иначе время, проведённое игроком
  // в самой рекламе, засчитывалось бы в паузу до следующей.
  showAdCountdown(scene, () => Ads.showFullscreen({ onClose: done }));
}

// Для тестов и для перезапуска сессии: сбросить интервал.
export function resetInterstitial() { lastAt = 0; }
