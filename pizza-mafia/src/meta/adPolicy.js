// ПРАВИЛО ПОКАЗА ПОЛНОЭКРАННОЙ РЕКЛАМЫ — чистая функция, без Phaser и без SDK.
//
// Вынесено отдельно от ui/interstitial.js намеренно: там сцена, отсчёт и вызов площадки,
// то есть проверить руками можно только в браузере. Само же решение «показывать или нет» —
// арифметика, и она обязана быть под тестом: монетизация тихо ломается именно здесь
// (в этой игре модуль отсчёта пролежал в папке невызванным, и никто этого не заметил).

/**
 * Пора ли показывать полноэкранную.
 * @param {number} now — текущее время, мс
 * @param {number} lastAt — время начала прошлого показа, мс (0 — показов ещё не было)
 * @param {number} intervalMs — минимальный интервал между показами
 */
export function canShowInterstitial(now, lastAt, intervalMs) {
  if (!lastAt) return true;               // первый переход за сессию — показываем всегда
  if (now < lastAt) return true;          // часы перевели назад — не запираем показы навечно
  return now - lastAt >= intervalMs;
}
