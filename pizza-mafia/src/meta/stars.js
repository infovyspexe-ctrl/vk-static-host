// ЗВЁЗДЫ ЗА СМЕНУ. Чистая логика оценки, без Phaser и без i18n.
//
// ПОЧЕМУ ПЕРЕПИСАНО. Раньше звёзды считались по доле обслуженных:
// обслужил/(обслужил+ушло), три звезды при 0.9. После того как очередь ограничили пятью
// местами, гости перестали УХОДИТЬ вовсе — при полной очереди новый гость просто не
// приходит. Знаменатель стал равен числителю, доля всегда 1.0, и три звезды выдавались
// каждую смену независимо от того, как игрок играл. Замер пяти смен подряд: 3 звезды,
// 3 звезды, 3 звезды, 3 звезды, 3 звезды.
//
// Теперь оценка идёт по ВЫРУЧКЕ относительно цели смены, а цель берётся из того же места,
// что и дань района: сколько надо зарабатывать в среднем, чтобы расплатиться с Доном к
// концу района. Это связывает оценку смены с единственной целью, которая у игрока есть,
// вместо отдельной шкалы «непонятно за что».
//
// Ушедшие гости остаются, но как ПОТОЛОК, а не как основа: сколько бы ты ни заработал,
// с потерянными гостями трёх звёзд не будет. Иначе можно было бы намеренно бросать
// сложные заказы ради быстрых.

// Сколько ушедших гостей ещё допускает две звезды. Больше — одна.
const LOST_FOR_ONE_STAR = 3;

// coins  — выручка смены (то, что уходит в дань)
// lost   — сколько гостей ушло
// target — целевая выручка смены (дань района / число смен); 0 = цели нет, оценка по потерям
// t      — пороги из ECONOMY.starTargets: доли цели на три и на две звезды
export function shiftStars({ coins = 0, lost = 0, target = 0, thresholds }) {
  const t = thresholds || { three: 1.5, two: 0.7 };

  let stars;
  if (target > 0) {
    const frac = coins / target;
    stars = frac >= t.three ? 3 : frac >= t.two ? 2 : 1;
  } else {
    // Бесконечный режим без цели: оценивать нечем, кроме аккуратности.
    stars = lost === 0 ? 3 : lost < LOST_FOR_ONE_STAR ? 2 : 1;
  }

  if (lost > 0) stars = Math.min(stars, 2);
  if (lost >= LOST_FOR_ONE_STAR) stars = 1;
  return stars;
}

// Доля цели, набранная за смену (для полосы в интерфейсе). Без цели — 1.
export function shiftGoalFraction(coins, target) {
  if (!(target > 0)) return 1;
  return Math.max(0, coins / target);
}
