// Цена следующего уровня ветки. level = сколько УЖЕ куплено (значит, цена уровня level+1).
export function upgradeCost(id, level) {
  const u = UPGRADES[id];
  return Math.round(u.costBase * Math.pow(u.costMult, level));
}

// Эффект (суммарный вклад) для уровня ветки. Применение эффекта — в kitchen/orders/сцене.
export function upgradeEffect(id, level) {
  return UPGRADES[id].effectPer * level;
}

