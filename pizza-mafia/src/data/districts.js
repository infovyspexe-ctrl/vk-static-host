// РАЙОНЫ КАМПАНИИ. Только числа и состав, никакой логики (она — в meta/campaign.js).
//
// Зачем районы вообще. В первой версии игра была бесконечной чередой «дней»: рецепты
// открывались днями 1–7, персонажи — днями 1–5, апгрейды упирались в потолок, и с 8-го
// дня игрок видел ровно то же, что на 7-м, до бесконечности. Плюс торопиться было не за
// чем: единственным давлением был таймер терпения.
//
// Район = 5–6 смен с общей целью: собрать дань к его концу. Дань даёт причину считать
// деньги и торопиться, а смена района — ощутимую награду (новый фон, рецепты, гости).
// Последняя смена района — заказ Дона: условие «ни одного ушедшего гостя».
//
// Поля:
//   id        — ключ локализации (district_<id>) и имя фона
//   shifts    — сколько смен в районе
//   tribute   — сколько монет надо собрать за район, чтобы уйти дальше.
//               Формула: 0.65 × смен × ожидаемая выручка смены. Коэффициент учитывает,
//               что живой игрок выдаёт 70–80% расчётного потолка. Дань должна
//               закрываться на последней-предпоследней смене района: закроется раньше —
//               давление исчезнет на середине.
//
//               ЧИСЛА ПЕРЕСЧИТАНЫ 2026-08-12 по живому прогону (NOTES.md). Формула была
//               верной, ошиблись во входных данных: ожидаемую выручку смены заложили в
//               ~400 монет, а измерено ~870–1000. Из-за этого дань первого района (1300)
//               закрывалась ВТОРОЙ сменой из пяти, и три последние шли вообще без цели —
//               провалиться было нельзя. Теперь вход в формулу — измеренная выручка.
//
//               ЧИСЛО, КОТОРОЕ ПРИДЁТСЯ УТОЧНИТЬ ПО ЖИВЫМ ИГРОКАМ. Разброс выручки смены
//               по темпу игрока большой: 828 у уверенного, 381 у медленного (замер без
//               апгрейдов и без удвоения за рекламу). Первый район поставлен по нижней
//               половине разброса — 2600 за пять смен, то есть 520 за смену. Медленному
//               игроку этого мало без ×2 за ролик или апгрейдов, и это осознанно: у него
//               есть и то и другое, а на крайний случай последняя смена переигрывается
//               («Дон даёт отсрочку»). Если метрика покажет, что первый район валят массово,
//               снижать надо ЭТО число, а не трогать темп смены.
//   recipes   — какие рецепты район ОТКРЫВАЕТ (доступно и всё из пройденных)
//   customers — каких постоянных гостей район открывает
//   bg        — ключ текстуры фона (пока рисуется кодом, ассет подключится позже)
