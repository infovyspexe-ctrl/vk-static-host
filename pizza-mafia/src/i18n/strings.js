export const i18n = {
  lang: 'ru',

  // Нормализуем к 2-буквенному коду: площадка может вернуть 'en-US', а таблица ждёт 'en'.
  // НЕЗНАКОМЫЙ язык уводит на en, а не молча остаётся на дефолтном ru (п.8.2.3) — критичный
  // фикс шаблона v35: недоступный SDK без этой ветки давал русский любому модератору с
  // английским браузером, реальный отказ п.2.14 («Осуши озеро», «Рубеж»). Перенесено 24.08.
  init(lang) {
    const code = String(lang || '').slice(0, 2).toLowerCase();
    if (STRINGS[code]) this.lang = code;
    else if (code) this.lang = 'en';
  },

  // t('day', { n: 3 }) -> 'День 3'. Незнакомый ключ падает на русский, потом на сам ключ.
  t(key, params) {
    const table = STRINGS[this.lang] || STRINGS.ru;
    let s = table[key] ?? STRINGS.ru[key] ?? key;
    if (params) {
      for (const p in params) s = s.split('{' + p + '}').join(String(params[p]));
    }
    return s;
  }
};
